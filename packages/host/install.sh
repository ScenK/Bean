#!/bin/sh
# bean-core installer (#836), shipped at the top of bean-core-<ver>.tar.gz. Installs this tarball's
# core as a service for the account that runs it: a LaunchAgent on macOS, a systemd unit on Linux.
#
#   ./install.sh [--tz <Area/City>]   install, or upgrade to this tarball's version
#   ./install.sh --uninstall          remove the service, the wrapper and the versions; keep ~/.bean
#   bean-core rollback                swap the current and previous versions, restart the service
#   ./install.sh --restart            restart the service on `current` (after `bean-core update`)
#
# Run it as the account the core serves, not root: it uses sudo only for /usr/local/bin/bean-core
# and, on Linux, the unit file and systemctl. Versions live in ~/.local/share/bean-core/versions/<ver>/
# behind `current` and `previous` symlinks; the service and the wrapper run `current`, so an upgrade
# or a rollback is a link flip plus a restart. The wrapper hands `rollback` to current/install.sh.
set -eu

LABEL=dev.bean.core
MARKER="Generated by bean-core install.sh"
ENTRY=packages/host/dist/bean-core.js
# Test-only: a prefix for the root-owned paths below.
SYSROOT=${BEAN_CORE_SYSROOT:-}
WRAPPER=$SYSROOT/usr/local/bin/bean-core
UNIT=$SYSROOT/etc/systemd/system/bean-core.service

die() { printf 'bean-core install: %s\n' "$*" >&2; exit 1; }
say() { printf '%s\n' "$*"; }
usage() { sed -n '5,8s/^#  *//p' "$0"; }

# Values go into generated files (a shell script, a plist, a unit): refuse control characters (a
# newline would start a new line in any of them), then escape for each file's own syntax.
safe() {
  case $1 in *[[:cntrl:]]*) die "$2 contains a control character; refusing to write it into a service file." ;; esac
}
sh_quote() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }
xml_escape() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g' -e 's/"/\&quot;/g'; }
# systemd: specifiers are %, $ expands env vars, and quoted strings take C escapes.
sd_quote() { printf '"%s"' "$(printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/%/%%/g' -e 's/\$/$$/g')"; }
sd_raw() { printf '%s' "$1" | sed 's/%/%%/g'; }

[ -n "${HOME:-}" ] || die "HOME is not set."
[ "$(id -u)" != 0 ] || die "run this as the account the core serves, not root (it calls sudo where it must)."
OS=$(uname -s)
case $OS in Darwin | Linux) ;; *) die "unsupported OS $OS (macOS and Linux only)." ;; esac
safe "$HOME" "HOME"
ROOT=$HOME/.local/share/bean-core
UID_=$(id -u)
USER_=$(id -un)
LOG=$HOME/Library/Logs/bean-core.log

# --- the boot line -------------------------------------------------------------------------------

# Marks the log before a (re)start so wait_boot reads only what the new process writes.
mark_log() {
  if [ "$OS" = Darwin ]; then
    MARK=0
    if [ -f "$LOG" ]; then MARK=$(wc -l <"$LOG" | tr -d ' '); fi
  else
    MARK=$(date +%s)
  fi
}
log_since() {
  if [ "$OS" = Darwin ]; then
    [ -f "$LOG" ] && tail -n "+$((MARK + 1))" "$LOG"
  else
    sudo journalctl -u bean-core --since "@$MARK" -o cat --no-pager 2>/dev/null
  fi
}
wait_boot() {
  i=0
  while :; do
    out=$(log_since || true)
    line=$(printf '%s\n' "$out" | grep -m1 'bean-core on:' || true)
    if [ -n "$line" ]; then
      say "$line"
      return 0
    fi
    i=$((i + 1))
    [ "$i" -lt 30 ] || break
    sleep 1
  done
  err=$(printf '%s\n' "$out" | grep -m1 '^bean-core' || true)
  say "bean-core install: the service did not log its boot line within 30 s.${err:+ First error: $err}" >&2
  if [ "$OS" = Darwin ]; then say "Log: $LOG" >&2; else say "Log: journalctl -u bean-core" >&2; fi
  return 1
}
restart_service() {
  if [ "$OS" = Darwin ]; then
    launchctl kickstart -k "gui/$UID_/$LABEL"
  else
    sudo systemctl restart bean-core
  fi
}

# --- install -------------------------------------------------------------------------------------

node_hint() {
  cat >&2 <<EOF
bean-core needs Node 24 or newer (found: $1). Install it, then run this installer again:
  macOS:  brew install node
  Linux:  NodeSource (https://github.com/nodesource/distributions), Node 24.x
  nvm:    nvm install 24 (works, but the service breaks when that Node version is removed)
Nothing was changed.
EOF
}

detect_tz() {
  z=
  if [ "$OS" = Linux ] && command -v timedatectl >/dev/null 2>&1; then
    z=$(timedatectl show -p Timezone --value 2>/dev/null || true)
  fi
  if [ -z "$z" ]; then
    l=$(readlink /etc/localtime 2>/dev/null || true)
    case $l in *zoneinfo/*) z=${l#*zoneinfo/} ;; esac
  fi
  if [ -z "$z" ] && [ -f /etc/timezone ]; then z=$(cat /etc/timezone); fi
  printf '%s' "$z"
}

write_plist() {
  mkdir -p "$HOME/Library/LaunchAgents" "$HOME/Library/Logs"
  cat >"$HOME/Library/LaunchAgents/$LABEL.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- $MARKER -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>$(xml_escape "$node")</string>
    <string>$(xml_escape "$ROOT/current/$ENTRY")</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict><key>TZ</key><string>$(xml_escape "$tz")</string></dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>$(xml_escape "$LOG")</string>
  <key>StandardErrorPath</key><string>$(xml_escape "$LOG")</string>
</dict>
</plist>
EOF
}

write_unit() {
  cat >"$tmp" <<EOF
# $MARKER
[Unit]
Description=Bean core (sprouts, reminders, chat bots)
After=network-online.target
Wants=network-online.target

[Service]
User=$(sd_raw "$USER_")
WorkingDirectory=$(sd_raw "$HOME")
Environment=$(sd_quote "TZ=$tz")
ExecStart=$(sd_quote "$node") $(sd_quote "$ROOT/current/$ENTRY")
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
  sudo mkdir -p "$(dirname "$UNIT")"
  sudo install -m 644 "$tmp" "$UNIT"
}

install_core() {
  src=$(cd -P "$(dirname "$0")" && pwd)
  [ -f "$src/$ENTRY" ] || die "no $ENTRY beside install.sh; run the install.sh inside the extracted bean-core-<ver>/ directory."

  # Preflight: nothing changes until every check passes.
  node=$(command -v node || true)
  have=
  [ -n "$node" ] && have=$("$node" -p 'process.versions.node' 2>/dev/null || true)
  major=${have%%.*}
  case $major in '' | *[!0-9]*) major=0 ;; esac
  if [ "$major" -lt 24 ]; then
    node_hint "${have:-none}${node:+ at $node}"
    exit 1
  fi
  case $node in /*) ;; *) die "node resolves to a relative path ($node); put an absolute Node 24 directory on PATH." ;; esac
  safe "$node" "the node path"
  case $node in */.nvm/*) say "warning: $node is an nvm Node; the service breaks if that version is removed. Re-run this installer after switching Node." >&2 ;; esac

  vline=$("$node" "$src/$ENTRY" --version) || die "$src/$ENTRY --version failed."
  ver=$(printf '%s' "$vline" | sed -n 's/^bean-core \([0-9A-Za-z][0-9A-Za-z.+_-]*\) contract [0-9][0-9]*$/\1/p')
  [ -n "$ver" ] || die "unexpected --version output: $vline"

  [ -n "$tz" ] || tz=$(detect_tz)
  [ -n "$tz" ] || die "could not detect the time zone; pass --tz <Area/City> (e.g. --tz America/Toronto)."
  safe "$tz" "the time zone"
  printf '%s' "$tz" | grep -Eq '^[A-Za-z0-9_+-]+(/[A-Za-z0-9_+-]+)*$' || die "bad time zone: $tz"
  "$node" -e 'new Intl.DateTimeFormat("en", { timeZone: process.argv[1] })' "$tz" 2>/dev/null ||
    die "unknown time zone: $tz (pass --tz <Area/City>)."

  say "Installing bean-core $ver (TZ=$tz, node $have at $node). sudo writes $WRAPPER$([ "$OS" = Linux ] && printf ' and %s' "$UNIT")."
  sudo -v || die "sudo is needed for $WRAPPER. Nothing was changed."

  # The version, then the links. Re-running from inside the installed copy reinstalls nothing.
  mkdir -p "$ROOT/versions"
  dest=$ROOT/versions/$ver
  if [ "$(cd -P "$dest" 2>/dev/null && pwd || true)" != "$src" ]; then
    rm -rf "$dest.tmp"
    cp -R "$src" "$dest.tmp"
    rm -rf "$dest"
    mv "$dest.tmp" "$dest"
  fi
  old=$(readlink "$ROOT/current" 2>/dev/null || true)
  if [ "$old" != "versions/$ver" ]; then
    [ -z "$old" ] || ln -sfn "$old" "$ROOT/previous"
    ln -sfn "versions/$ver" "$ROOT/current"
  fi

  # bean-core exits without a config; an empty key boots it, and the shell's Settings sets the key.
  if [ ! -e "$HOME/.bean/config.json" ]; then
    mkdir -p "$HOME/.bean"
    chmod 700 "$HOME/.bean"
    (umask 077 && printf '{ "openaiApiKey": "" }\n' >"$HOME/.bean/config.json")
    say "Wrote ~/.bean/config.json with an empty key; paste the OpenAI key in the shell's Settings."
  fi

  # A non-interactive SSH session has a minimal PATH, so the wrapper uses absolute paths.
  tmp=$(mktemp)
  trap 'rm -f "$tmp"' EXIT
  {
    printf '#!/bin/sh\n# %s. `bean-core rollback` swaps current and previous, then restarts the service.\n' "$MARKER"
    printf 'if [ "${1:-}" = rollback ]; then exec /bin/sh %s --rollback; fi\n' "$(sh_quote "$ROOT/current/install.sh")"
    printf 'exec %s %s "$@"\n' "$(sh_quote "$node")" "$(sh_quote "$ROOT/current/$ENTRY")"
  } >"$tmp"
  sudo mkdir -p "$(dirname "$WRAPPER")"
  sudo install -m 755 "$tmp" "$WRAPPER"

  if [ "$OS" = Darwin ]; then
    write_plist
    mark_log
    launchctl bootout "gui/$UID_/$LABEL" 2>/dev/null || true
    # bootout returns before the old job is gone; bootstrap fails until it is.
    n=0
    until launchctl bootstrap "gui/$UID_" "$HOME/Library/LaunchAgents/$LABEL.plist" 2>/dev/null; do
      n=$((n + 1))
      [ "$n" -lt 5 ] || die "launchctl bootstrap failed. A LaunchAgent needs $USER_ logged in at the Mac (a GUI session)."
      sleep 1
    done
  else
    write_unit
    sudo systemctl daemon-reload
    sudo systemctl enable --quiet bean-core
    mark_log
    sudo systemctl restart bean-core
  fi

  wait_boot || exit 1
  [ "$OS" = Linux ] || say "A LaunchAgent starts at login: for unattended reboots, turn on automatic login for $USER_ (System Settings > Users & Groups)."
  say "Add this core in Bean: $USER_@$(hostname)"
}

# --- rollback / uninstall ------------------------------------------------------------------------

rollback() {
  cur=$(readlink "$ROOT/current" 2>/dev/null) || die "bean-core is not installed ($ROOT/current is missing)."
  prev=$(readlink "$ROOT/previous" 2>/dev/null) || die "there is no previous version to roll back to."
  [ -d "$ROOT/$prev" ] || die "$ROOT/$prev is missing."
  ln -sfn "$cur" "$ROOT/previous"
  ln -sfn "$prev" "$ROOT/current"
  say "Rolled back to ${prev#versions/} (previous is now ${cur#versions/}); restarting."
  mark_log
  restart_service
  wait_boot || exit 1
}

restart() {
  [ -L "$ROOT/current" ] || die "bean-core is not installed ($ROOT/current is missing)."
  mark_log
  restart_service
  wait_boot || exit 1
}

uninstall() {
  if [ "$OS" = Darwin ]; then
    launchctl bootout "gui/$UID_/$LABEL" 2>/dev/null || true
    rm -f "$HOME/Library/LaunchAgents/$LABEL.plist"
  elif [ -f "$UNIT" ]; then
    sudo systemctl disable --now --quiet bean-core || true
    sudo rm -f "$UNIT"
    sudo systemctl daemon-reload
  fi
  if [ -f "$WRAPPER" ]; then
    if grep -q "$MARKER" "$WRAPPER"; then sudo rm -f "$WRAPPER"; else say "Left $WRAPPER: this installer did not write it."; fi
  fi
  rm -rf "$ROOT"
  say "bean-core is uninstalled. Kept ~/.bean (config, memories, notes, sprouts); delete it yourself if you want it gone."
}

mode=install
tz=
while [ $# -gt 0 ]; do
  case $1 in
    --tz) [ $# -ge 2 ] || die "--tz needs a zone (e.g. --tz America/Toronto)."; tz=$2; shift 2 ;;
    --tz=*) tz=${1#--tz=}; shift ;;
    --uninstall) mode=uninstall; shift ;;
    --rollback) mode=rollback; shift ;;
    --restart) mode=restart; shift ;;
    -h | --help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
  esac
done

case $mode in
  install) install_core ;;
  rollback) rollback ;;
  restart) restart ;;
  uninstall) uninstall ;;
esac
